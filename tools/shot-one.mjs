import { chromium } from 'playwright';
const browser = await chromium.launch({ args: ['--no-sandbox','--use-gl=swiftshader','--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 860 } });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
page.on('console', m => { if (m.type() === 'error') errors.push(m.text().slice(0,160)); });
await page.goto('http://localhost:5173/', { waitUntil: 'domcontentloaded' });
await page.waitForSelector('.menu:not(.is-hidden)', { timeout: 60000 });
await page.click('.menu-list__button:has-text("Играть")');
await page.waitForFunction(() => window.viceShore?.machine?.current === 'playing' && !window.viceShore?.machine?.isBusy, null, { timeout: 60000 });
await page.keyboard.press('F3');
await page.waitForTimeout(2000);
await page.evaluate(() => window.viceShore.setInspectorAngle(0));
await page.waitForTimeout(1500);
await page.screenshot({ path: 'shots/char-12-front-final.png' });
await page.evaluate(() => { window.viceShore.setInspectorAngle(0); window.viceShore.zoomInspector(-2.1); });
await page.waitForTimeout(1800);
await page.screenshot({ path: 'shots/char-13-face-final.png' });
console.log(JSON.stringify({ errors }));
await browser.close();
